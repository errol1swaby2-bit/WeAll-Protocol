#!/usr/bin/env python3
"""Fail-closed public-only post-restart witness for the IHD-1 browser custody gate.

The input is generated by the real browser test AFTER its signed transactions
have succeeded. It contains only synthetic account ID, public-key digest,
public profile text, and transaction/block identifiers: never recovery keys,
private witness material, sessions, cookies, or PoH evidence.

This is a controlled-devnet persistence rehearsal, not BFT or independent-node
finality evidence.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import time
from pathlib import Path
from typing import Any
from urllib.parse import quote
from urllib.request import urlopen


def fail(code: str) -> None:
    raise SystemExit(f"FAILED IHD1 post-restart public witness: {code}")


def _read_json(url: str) -> dict[str, Any]:
    with urlopen(url, timeout=5) as response:
        value = json.load(response)
    if not isinstance(value, dict):
        fail("non_object_api_response")
    return value


def _required_text(obj: dict[str, Any], key: str) -> str:
    value = obj.get(key)
    if not isinstance(value, str) or not value.strip():
        fail(f"missing_{key}")
    return value.strip()


def check_evidence(path: Path) -> dict[str, Any]:
    if not path.is_file() or path.stat().st_size > 8192:
        fail("missing_or_oversized_public_witness")
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        fail("invalid_public_witness_json")
    if not isinstance(value, dict) or value.get("format") != "weall-ihd1-public-receipts-v1":
        fail("unexpected_witness_version")
    account = _required_text(value, "account")
    if not re.fullmatch(r"@[A-Za-z0-9_]{4,64}", account):
        fail("unexpected_synthetic_account")
    digest = _required_text(value, "account_pubkey_sha256")
    if not re.fullmatch(r"[a-f0-9]{64}", digest):
        fail("invalid_key_commitment")
    _required_text(value, "profile_display_name")
    for name in ("account_register", "profile_update"):
        record = value.get(name)
        if not isinstance(record, dict):
            fail(f"missing_{name}")
        _required_text(record, "tx_id")
        block_id = _required_text(record, "block_id")
        if not re.fullmatch(r"[a-f0-9]{64}", block_id):
            fail(f"invalid_{name}_block_id")
        height = record.get("height")
        if not isinstance(height, int) or height < 1:
            fail(f"invalid_{name}_height")
    return value


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--evidence", type=Path, required=True)
    ap.add_argument("--api", default="http://127.0.0.1:8001")
    ap.add_argument("--wait-seconds", type=int, default=90)
    args = ap.parse_args()

    witness = check_evidence(args.evidence)
    root = args.api.rstrip("/")
    deadline = time.monotonic() + max(1, args.wait_seconds)

    while time.monotonic() < deadline:
        try:
            ready = _read_json(f"{root}/v1/readyz")
            identity = _read_json(f"{root}/v1/chain/identity")
            if ready.get("ok") is True and identity.get("chain_id") == "weall-controlled-devnet":
                break
        except Exception:
            pass
        time.sleep(1)
    else:
        fail("restarted_controlled_devnet_not_ready")

    for name in ("account_register", "profile_update"):
        expected = witness[name]
        receipt = _read_json(f"{root}/v1/tx/status/{quote(expected['tx_id'], safe='')}")
        if receipt.get("status") != "confirmed":
            fail(f"{name}_not_confirmed_after_restart")
        if receipt.get("apply_ok") is not True or receipt.get("local_state_synced") is False:
            fail(f"{name}_apply_or_state_unverified_after_restart")
        if int(receipt.get("height") or 0) != expected["height"]:
            fail(f"{name}_height_changed_after_restart")
        if str(receipt.get("block_id") or "") != expected["block_id"]:
            fail(f"{name}_block_identity_changed_after_restart")

    account = witness["account"]
    account_path = quote(account, safe="")
    public_account = _read_json(f"{root}/v1/accounts/{account_path}")
    state = public_account.get("state")
    if not isinstance(state, dict):
        fail("registered_account_state_missing")
    pubkey_hex = str(state.get("pubkey") or "")
    if not re.fullmatch(r"[0-9a-f]{3904}", pubkey_hex):
        fail("canonical_account_pubkey_not_hex_mldsa65")
    observed_hash = hashlib.sha256(bytes.fromhex(pubkey_hex)).hexdigest()
    if observed_hash != witness["account_pubkey_sha256"]:
        fail("account_signing_authority_changed_after_restart")
    if int(state.get("poh_tier") or 0) != 0:
        fail("synthetic_tier_zero_account_unexpectedly_advanced")
    if int(state.get("nonce") or 0) < 2:
        fail("account_nonce_did_not_persist")

    profile = _read_json(f"{root}/v1/accounts/{account_path}/profile")
    if witness["profile_display_name"] not in json.dumps(profile, ensure_ascii=False):
        fail("committed_profile_content_missing_after_restart")

    print("PASS: both signed transaction receipts survived controlled-devnet backend restart")
    print("PASS: same canonical ML-DSA signing authority, Tier-0 standing, nonce and profile")
    print("NOT_PROVED: independent node, BFT finality, live PoH, uniqueness or constitutional approval")
    return 0


if __name__ == "__main__":
    sys.exit(main())
